const checkSingleHandleStates = async (key, field, label, valid) => {
  const input = 'vas-time-'+key+'-'+field, grip = 'vas-slider-'+key+'-'+field, limit = 'vas-limit-'+key+'-'+field;
  const samples = [];
  for (const [entered, reason, error] of [
    ['', '未填写', /设定时间/], ['xy:zz','不能采用',/有效/], ['99:00','不能采用',/超过/],
  ]) {
    await p.fill('#'+input, entered);
    const [hint, aria, details] = await Promise.all([current(limit), current(grip,'aria-valuetext'), current('vas-error-'+key)]);
    assert.ok(hint.includes('滑块为建议位置：'+label+'时间'+reason));
    assert.ok(aria.endsWith('，建议位置，'+label+'时间'+reason));
    assert.match(details,error);
    assert.match(await current(grip,'aria-describedby'),new RegExp('vas-error-'+key));
    assert.equal(await value(input),entered);
    assert.equal(await disabled('vas-save'),true);
    if (entered==='99:00') await shot('single-'+key+'-invalid-360');
    samples.push({entered,hint,aria,details});
  }
  await p.fill('#'+input,valid);
  assert.equal(await current(grip,'aria-valuetext'),valid);
  assert.doesNotMatch(await current(limit),/建议位置/);
  assert.equal(await visible('vas-error-'+key),false);
  return {key,field,samples,restored:valid};
};
