const inspectTrack = key => p.evaluate(key => {
  const track = document.querySelector('#vas-track-' + key + ' svg');
  const selection = track.querySelector('[data-selection]');
  const handles = [...track.querySelectorAll('[role=slider]')].map(node => {
    const box = node.querySelector('rect').getBoundingClientRect();
    const x = box.x + box.width / 2, y = box.y + box.height / 2;
    const field = node.dataset.endpoint;
    return {field, x, y, width:box.width, height:box.height, target:document.elementFromPoint(x,y)?.closest('[role=slider]')?.id,
      mark:node.querySelector('text').textContent, name:node.getAttribute('aria-label'), value:Number(node.getAttribute('aria-valuenow')),
      anchor:node.transform.baseVal.getItem(0).matrix.e, time:document.querySelector('#vas-time-' + key + '-' + field).value};
  });
  return {host:document.querySelector('.preview-device').getBoundingClientRect().width, viewport:innerWidth, handles,
    selection:{visible:getComputedStyle(selection).visibility === 'visible', start:selection.x1.baseVal.value, end:selection.x2.baseVal.value},
    svg:{left:track.getBoundingClientRect().left, right:track.getBoundingClientRect().right}};
}, key);
const verifyTrack = (g, key, type) => {
  assert.equal(g.handles.length,2);
  const [start,end] = g.handles;
  assert.deepEqual(g.handles.map(h=>h.mark), ['始','终']);
  assert.deepEqual(g.handles.map(h=>h.name), [type+'开始时间',type+'结束时间']);
  assert.equal(start.y,end.y);
  assert.ok(start.x + start.width/2 <= end.x - end.width/2 + .05, JSON.stringify(g));
  for (const h of g.handles) {
    assert.ok(h.width >= 24 && h.height >= 24, JSON.stringify(h));
    assert.equal(h.target,'vas-slider-'+key+'-'+h.field);
    assert.equal(h.time, [Math.floor(h.value/60),h.value%60].map(n=>String(n).padStart(2,'0')).join(':'));
  }
  assert.ok(g.selection.visible && g.selection.end > g.selection.start, JSON.stringify(g));
  assert.ok(Math.abs(g.selection.start - start.anchor) < .001 && Math.abs(g.selection.end - end.anchor) < .001);
};
