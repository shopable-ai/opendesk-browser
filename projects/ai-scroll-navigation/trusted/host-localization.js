// Pure project state descriptions; raw external messages remain literal text.
export function scrollNavigationMessageText(locale,description){
  if(!description)return '';
  if(typeof description!=='object')return String(description);
  const params=Object.fromEntries(Object.entries(description.parameters||{}).map(([key,value])=>
    [key,value&&typeof value==='object'?scrollNavigationMessageText(locale,value):value]));
  return scrollNavigationText(locale,description.key,params);
}
