export type ErrorCode = typeof legacyErrorCodes[keyof typeof legacyErrorCodes] | 'errGeneric' | 'errDuplicateId' | 'errRestoredPreviousRoute';
export function errorCodeOf(message: string): ErrorCode {
  if (message.startsWith('应用失败；代理控制权已释放，会话凭证清理尚未完成')) return 'errSessionCleanupPending';
  if (message.startsWith('应用失败且控制权未能确认释放')) return 'errReleaseUnconfirmed';
  if (message.startsWith('应用失败，原线路已恢复：')) return 'errRestoredPreviousRoute';
  if (message.endsWith(' 的 ID 重复')) return 'errDuplicateId';
  return legacyErrorCodes[message as keyof typeof legacyErrorCodes] ?? 'errGeneric';
}
