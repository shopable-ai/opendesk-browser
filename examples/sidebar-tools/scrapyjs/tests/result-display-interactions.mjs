import {readFile} from 'node:fs/promises';

// Exercise the actual React components with the original offline SDK fixture.
export async function exerciseResultDisplay(page,url,{screenshot=async()=>{}}={}){
  const checks=[],check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
  await page.goto(url);
  const f=page.frameLocator('#opendesk-preview-frame'),get=id=>f.locator('#'+id);
  await get('start').waitFor();
  check(await get('custom-csv').count()===0,'custom download is absent before results');
  await get('tab-rules').click();
  check(await f.getByRole('switch',{name:'显示名称',exact:true}).count()===0,'rules have no display-mode switch');
  await get('csv-preset').locator('summary').click();
  const preset=get('csv-preset').getByRole('textbox',{name:'title 显示名称',exact:true});
  await preset.fill('标题');await preset.press('Enter');
  check((await get('csv-preset').locator('.csv-header-preview th').allTextContents()).join(',')==='标题','human can preconfigure one CSV name before capture');
  await screenshot('01-preset-before-capture');
  await get('tab-json').click();
  const config=JSON.parse(await get('config-json').inputValue());
  check(config.output.fieldNames.title==='标题'&&config.itemConfig.title==='.::text','preset is declarative metadata and preserves the selector');
  config.output.fieldNames.source='来源';
  await get('config-json').fill(JSON.stringify(config,null,2));
  await get('tab-results').click();await get('start').click();await get('run-summary').filter({hasText:'采集完成'}).waitFor();
  const headers=()=>get('record-table').locator('thead th').allTextContents();
  const rawHeaders=await headers();
  await screenshot('02-results-downloads');
  await get('custom-csv').click();
  const input=get('custom-csv-settings').getByRole('textbox',{name:'title 显示名称',exact:true});
  const source=get('custom-csv-settings').getByRole('textbox',{name:'source 显示名称',exact:true});
  const preview=()=>get('custom-csv-settings').locator('.csv-header-preview th').allTextContents();
  check(await input.inputValue()==='标题'&&await source.inputValue()==='来源','manual and programmatic names prefill the custom export');
  check(await get('custom-csv-settings').getByRole('textbox').count()===2&&await get('custom-csv-settings').getByRole('button').count()===2,'only one input per field plus download and cancel');
  check(await get('custom-csv-settings').getByRole('button',{name:/调整.*顺序|显示列/}).count()===0,'custom CSV has no sorting or visibility controls');
  await input.fill('书名');
  check((await preview()).join(',')==='书名,来源','CSV preview updates in actual export order');
  check(JSON.stringify(await headers())===JSON.stringify(rawHeaders),'custom CSV labels leave the result table unchanged');
  await input.press('Escape');
  check(await input.inputValue()==='标题'&&await get('custom-csv-settings').isVisible(),'Escape restores the current name without closing the form');
  await input.fill('书名');await input.press('Enter');
  await screenshot('03-custom-csv');
  let pending=page.waitForEvent('download');await get('download-custom-csv').click();
  const custom=await readFile(await(await pending).path(),'utf8');
  check(custom.startsWith('"书名","来源"\r\n')&&custom.split('\r\n').length===3,'custom CSV downloads both complete records with selected labels');
  pending=page.waitForEvent('download');await get('download-csv').click();
  const raw=await readFile(await(await pending).path(),'utf8');
  check(raw.startsWith('"title","source"\r\n')&&raw.slice(raw.indexOf('\r\n'))===custom.slice(custom.indexOf('\r\n')),'original CSV stays byte-identical below its original headers');
  pending=page.waitForEvent('download');await get('download-json').click();
  const json=JSON.parse(await readFile(await(await pending).path(),'utf8'));
  check(json.result.data.length===2&&Object.hasOwn(json.result.data[0],'title')&&!Object.hasOwn(json.result.data[0],'书名'),'JSON retains original keys and all records');
  await source.fill('书名');
  check(await get('download-custom-csv').isDisabled()&&await get('custom-csv-settings').getByRole('alert').isVisible(),'duplicate custom headers block only custom download');
  await source.fill('');
  check((await preview()).join(',')==='书名,source'&&!await get('download-custom-csv').isDisabled(),'blank name falls back to its raw key');
  await get('cancel-custom-csv').click();
  await get('custom-csv').evaluate(el=>new Promise(resolve=>requestAnimationFrame(()=>resolve(el===document.activeElement)))).then(ok=>check(ok,'cancel restores focus to custom download entry'));
  check(await get('custom-csv-settings').count()===0,'cancel collapses the custom export');
  await get('custom-csv').click();
  check(await input.inputValue()==='标题'&&await source.inputValue()==='来源','reopening discards per-download edits and restores profile presets');
  await get('csv-settings-heading').press('Escape');
  check(await get('custom-csv-settings').count()===0,'Escape outside an input collapses the form');
  await get('tab-json').click();
  check(JSON.parse(await get('config-json').inputValue()).output.fieldNames.title==='标题','per-download edits never mutate the saved configuration draft');
  await get('tab-rules').click();
  const rule=f.getByRole('textbox',{name:'采集规则 title',exact:true});
  const oldRule=await rule.inputValue();await rule.fill('');await get('tab-results').click();
  check(await get('custom-csv').isDisabled()&&await get('start').isDisabled(),'unapplied rule drafts retain run and custom-editor locks');
  await get('tab-rules').click();check(await rule.inputValue()==='','cross-tab rule draft survives');await rule.press('Escape');
  check(await rule.inputValue()===oldRule,'cancel restores the original selector');
  await get('tab-results').click();
  // The existing save action persists the same metadata, without running a task.
  await get('manage-profiles').click();
  await get('library-save-config').click();
  await get('library-current').filter({hasText:'配置已保存'}).waitFor();
  check(await get('library-current').filter({hasText:'配置已保存'}).isVisible(),'preset saves through the original conditional configuration storage');
  await page.locator('#sidebar-tool-back').click();await get('tab-results').waitFor({state:'visible'});
  await get('custom-csv').click();
  check(await input.inputValue()==='标题','saving and returning retains the preset');
  return checks;
}
