// Run with a Playwright Page against preview/dev.html or the offline preview.
// It exercises the real React UI with the preview's explicitly simulated SDK.
export async function exercisePreview(page,url){
  const checks=[],errors=[];
  const check=(condition,label)=>{if(!condition)throw Error(label);checks.push(label);};
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url);
  let frame;
  const connect=async()=>{frame=page.frameLocator('#opendesk-preview-frame');await frame.locator('#profile-list').waitFor();};
  const scenario=async name=>{await page.locator('#scrapyjs-preview-scenario').selectOption(name);await connect();};
  const value=id=>frame.locator('#'+id).inputValue();
  const press=id=>frame.locator('#'+id).click();
  await connect();
  await frame.locator('#app-notice').filter({hasText:'已读取保存配置'}).waitFor();
  check(await frame.locator('#start').isEnabled(),'ready to run through existing adapter');
  await press('tab-rules');await frame.locator('[data-field-key="title"]').click();
  check(await value('field-key')==='title','loads the selected field');
  await frame.locator('#field-selector').fill('h2 a');
  check(await frame.locator('#start').isDisabled()&&await frame.locator('#save-config').isDisabled(),'unapplied field blocks Run and Save');
  await press('tab-results');await press('tab-rules');
  check(await value('field-selector')==='h2 a','tabs preserve field draft');
  await frame.locator('#profile-list').selectOption('douban');
  await frame.locator('#profile-confirm').waitFor({state:'visible'});
  check(await value('profile-list')==='demo','dirty switch displays actual selected profile');
  await frame.locator('#profile-confirm-cancel').press('Escape');
  check(await value('field-selector')==='h2 a','Escape cancels switch without discarding draft');
  await press('apply-field');
  check(JSON.parse(await value('config-json')).itemConfig.title==='h2 a::text','applied field reaches real App Model config');
  await frame.locator('#field-key').fill('heading');await press('apply-field');
  await frame.locator('#field-selector').fill('h3 a');await press('apply-field');
  let config=JSON.parse(await value('config-json'));
  check(config.itemConfig.heading==='h3 a::text'&&!Object.hasOwn(config.itemConfig,'title'),'rename followed by edit keeps one field identity');
  await frame.locator('#field-key').fill('title');await press('apply-field');
  await press('new-field');await frame.locator('#field-key').fill('link');await frame.locator('#field-selector').fill('a');
  await frame.locator('#field-read').selectOption('attr');await frame.locator('#field-attr').fill('href');await press('apply-field');
  await frame.locator('#field-key').fill('url');await press('apply-field');
  config=JSON.parse(await value('config-json'));
  check(config.itemConfig.url==='a::href'&&!Object.hasOwn(config.itemConfig,'link'),'new field can be renamed without leaving a duplicate');
  await press('remove-field');await frame.locator('#cancel-remove-field').press('Escape');
  check(Object.hasOwn(JSON.parse(await value('config-json')).itemConfig,'url'),'cancel field deletion preserves rule');
  await press('remove-field');await frame.getByRole('button',{name:'确认删除字段',exact:true}).click();
  check(!Object.hasOwn(JSON.parse(await value('config-json')).itemConfig,'url'),'confirmed field deletion updates config');
  await frame.locator('#crawl-editor summary').click();await frame.locator('#next-selector').fill('.next');await frame.locator('#max-pages').fill('2');
  check(await frame.locator('#start').isDisabled(),'unapplied pagination blocks Run');
  await press('apply-crawl');
  config=JSON.parse(await value('config-json'));
  check(config.nextPageSelector==='.next'&&config.maxPages===2,'pagination form applies to the original config');
  await press('save-config');await frame.locator('#profile-current').filter({hasText:'配置已保存'}).waitFor();
  await frame.locator('#json-editor summary').click();await frame.locator('#config-json').fill('{"unfinished');
  await press('tab-results');await press('tab-rules');
  check(await value('config-json')==='{"unfinished'&&await frame.locator('#start').isDisabled(),'invalid JSON survives tabs and blocks run');
  await frame.locator('#target-settings summary').click();
  check(await frame.locator('#target-url').isDisabled(),'target edit cannot overwrite malformed JSON');
  await press('new-profile');await press('profile-confirm-cancel');
  check(await value('config-json')==='{"unfinished','cancel new preserves malformed JSON');
  await press('new-profile');await press('profile-confirm-accept');
  check(await frame.locator('#start').isEnabled()&&await value('field-selector')==='','new clears accepted drafts');
  await press('save-config');await frame.locator('#profile-name').fill('新的采集');await press('profile-name-submit');
  await frame.locator('#profile-current').filter({hasText:'配置已保存'}).waitFor();
  check((await frame.locator('#profile-list option').allTextContents()).includes('新的采集'),'named config stored in preview memory');
  await frame.locator('#profile-management summary').click();await press('rename-profile');
  await frame.locator('#profile-name').fill('更名后的采集');await press('profile-name-submit');
  await frame.locator('#profile-naming').waitFor({state:'hidden'});
  check((await frame.locator('#profile-list option:checked').textContent())==='更名后的采集','rename updates selected configuration');
  await press('copy-profile');await frame.locator('#profile-name').fill('更名后的采集');await press('profile-name-submit');
  await frame.locator('#profile-name-error').filter({hasText:'名称'}).waitFor();
  check(await frame.locator('#profile-naming').isVisible(),'duplicate name keeps name form for correction');
  await frame.locator('#profile-name').fill('独立副本');await press('profile-name-submit');
  await frame.locator('#profile-naming').waitFor({state:'hidden'});
  check((await frame.locator('#profile-list option:checked').textContent())==='独立副本','copy selects an independent named configuration');
  await press('delete-profile');await press('profile-confirm-cancel');
  check((await frame.locator('#profile-list option:checked').textContent())==='独立副本','cancel configuration deletion preserves selection');
  await press('delete-profile');await press('profile-confirm-accept');
  await frame.locator('#profile-confirm').waitFor({state:'hidden'});
  check(!(await frame.locator('#profile-list option').allTextContents()).includes('独立副本'),'confirmed configuration deletion removes only the copy');
  await frame.locator('#profile-list').selectOption({label:'更名后的采集'});
  await frame.locator('#profile-current').filter({hasText:'配置已保存'}).waitFor();
  await press('start');await frame.locator('#run-summary').filter({hasText:'采集完成'}).waitFor({timeout:10000});
  check(await frame.locator('#record-table tbody tr').count()===2,'run renders simulated returned rows only after retirement');
  const download=page.waitForEvent('download');await press('download-csv');
  check((await download).suggestedFilename()==='SIMULATED-scrapyjs-result.csv','download explicitly identifies simulated data');
  await frame.locator('#profile-list').selectOption('demo');
  await frame.locator('#result-empty').waitFor({state:'visible'});
  check(await frame.locator('#export-actions').isHidden(),'switch clears old result ownership');
  await scenario('empty');await press('start');await frame.locator('#run-summary').filter({hasText:'采集完成'}).waitFor();
  check(await frame.locator('#record-table tbody tr').count()===0,'empty result is not invented');
  await scenario('error');await press('start');await frame.locator('#run-summary').filter({hasText:'请查看运行详情'}).waitFor();
  check(await frame.locator('#record-table tbody tr').count()===0,'failed result is not shown as success');
  await scenario('loading');await press('start');await frame.locator('#run-summary').filter({hasText:'正在采集'}).waitFor();
  check(await frame.locator('#profile-list').isDisabled(),'busy run locks profile changes');
  await press('stop');await frame.locator('#run-summary').filter({hasText:'采集已停止'}).waitFor();
  check(await frame.locator('#start').isEnabled(),'stop waits for original request retirement');
  await scenario('permission-denied');await frame.locator('#app-error').filter({hasText:'权限不足'}).waitFor();
  check(await frame.locator('#start').isDisabled(),'permission denied blocks Run');
  await scenario('untrusted');await press('start');await frame.locator('#run-summary').filter({hasText:'采集完成'}).waitFor();
  check(await frame.locator('#page-title img,#record-table script').count()===0,'untrusted title/records are text');
  check((await frame.locator('#record-table').textContent()).includes('<script>'),'untrusted record text remains visible');
  check(await page.locator('iframe').getAttribute('sandbox')==='allow-scripts allow-downloads','preview stays opaque');
  check(errors.length===0,'no React runtime errors');
  return {status:'PASS_SIMULATED_UI',checks,errors,realCapture:'NOT_TESTED'};
}
