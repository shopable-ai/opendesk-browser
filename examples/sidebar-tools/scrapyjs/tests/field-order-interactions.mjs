import {readFile} from 'node:fs/promises';

export async function exerciseFieldOrder(page,url,{screenshot=async()=>{}}={}){
 const checks=[],check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const f=page.frameLocator('#opendesk-preview-frame'),g=id=>f.locator('#'+id);
 const rules=()=>g('field-list').locator(':scope > .field-order-item').evaluateAll(rows=>rows.map(row=>row.dataset.fieldKey));
 const ruleHandle=key=>f.getByRole('button',{name:'调整字段顺序：'+key,exact:true});
 const displayHandle=key=>f.getByRole('button',{name:'调整显示顺序：'+key,exact:true});
 const config=async()=>{await g('tab-json').click();return JSON.parse(await g('config-json').inputValue());};
 await page.goto(url);await g('start').waitFor();await g('tab-json').click();
 const initial=JSON.parse(await g('config-json').inputValue());initial.itemConfig.source='.source::text';initial.output={fieldNames:{title:'标题',source:'来源'}};
 await g('config-json').fill(JSON.stringify(initial,null,2));await g('tab-rules').click();
 check((await rules()).join(',')==='title,source','rule order starts with the existing field order');
 await screenshot('05-rules-sortable');
 await ruleHandle('title').focus();await page.keyboard.press('Space');await page.keyboard.press('End');
 check(await ruleHandle('title').evaluate(el=>el===el.ownerDocument.activeElement),'continuous keyboard movement keeps focus on the picked-up field');
 await page.keyboard.press('Escape');
 check((await rules()).join(',')==='title,source','Escape cancels staged keyboard rule movement');
 await ruleHandle('title').focus();await page.keyboard.press('Space');await page.keyboard.press('End');await page.keyboard.press('Enter');
 check((await rules()).join(',')==='source,title','keyboard confirms collection field order');
 let value=await config();
 check(value.output.fieldOrder.join(',')==='source,title'&&value.itemConfig.title===initial.itemConfig.title&&value.itemConfig.source===initial.itemConfig.source,'rule order is explicit metadata and preserves selectors');
 await g('tab-rules').click();
 const first=await ruleHandle('source').boundingBox(),last=await ruleHandle('title').boundingBox();
 await page.mouse.move(first.x+first.width/2,first.y+first.height/2);await page.mouse.down();await page.mouse.move(last.x+last.width/2,last.y+last.height/2,{steps:10});await page.mouse.up();
 check((await rules()).join(',')==='title,source','mouse drag reorders collection fields');
 const titleRule=f.getByRole('textbox',{name:'采集规则 title',exact:true});await titleRule.fill('');
 check(await ruleHandle('source').isDisabled(),'invalid inline field draft blocks reordering');await titleRule.press('Escape');
 check(!await ruleHandle('source').isDisabled(),'restoring the last valid rule unlocks ordering');
 await g('save-config').click();await g('profile-current').filter({hasText:'配置已保存'}).waitFor();
 value=await config();check(value.output.fieldOrder.join(',')==='title,source','saving keeps the chosen rule order');
 await g('tab-results').click();await g('start').click();await g('run-summary').filter({hasText:'采集完成'}).waitFor();
 await g('edit-result-columns').click();
 await displayHandle('title').press('Space');await displayHandle('title').press('End');await displayHandle('title').press('Enter');
 const headers=()=>g('record-table').locator('thead th').allTextContents();
 check((await headers()).slice(1).join(',')==='source,title','display settings independently reorder the result table');
 await screenshot('06-display-sortable');
 await g('close-result-display').click();
 check(await g('edit-result-columns').evaluate(el=>el===document.activeElement),'closing display settings restores the entry focus');
 value=await config();check(value.output.fieldOrder.join(',')==='title,source','result ordering never changes saved collection field order');
 await g('tab-results').click();let pending=page.waitForEvent('download');await g('download-csv').click();
 const csv=await readFile(await(await pending).path(),'utf8');check(csv.startsWith('"title","source"\r\n'),'display ordering preserves original CSV export order');
 await g('custom-csv').click();
 check((await g('custom-csv-settings').locator('.csv-header-preview th').allTextContents()).join(',')==='标题,来源','custom CSV header preview follows actual export order independently');
 await g('cancel-custom-csv').click();await g('edit-result-columns').click();
 await g('reset-result-order').click();check((await headers()).slice(1).join(',')==='title,source','display reset restores default order');
 await g('close-result-display').click();await g('tab-rules').click();
 check((await rules()).join(',')==='title,source','returning to rules retains saved field order');
 await screenshot('07-rules-after-save');
 await f.getByRole('textbox',{name:'字段名 source',exact:true}).fill('origin');
 check(await f.getByRole('textbox',{name:'字段名 origin',exact:true}).evaluate(el=>el===document.activeElement),'renaming preserves field input focus after sorter integration');
 value=await config();check(value.output.fieldOrder.join(',')==='title,origin'&&value.output.fieldNames.origin==='来源','renaming carries field order and its custom CSV label');
 await g('tab-rules').click();await g('new-field').click();
 await f.getByRole('textbox',{name:'新字段名',exact:true}).pressSequentially('new_field');
 await f.getByRole('textbox',{name:'新字段采集规则',exact:true}).pressSequentially('.new::text');
 const added=f.getByRole('textbox',{name:'采集规则 new_field',exact:true});
 check(await added.inputValue()==='.new::text'&&await added.evaluate(el=>el===document.activeElement),'adding a valid rule retains focus as its row joins the sortable list');
 check((await rules()).join(',')==='title,origin,new_field','new fields append without losing chosen order');
 return checks;
}
