const root=new URL('../',import.meta.url);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
// Independent DOM reading, no ItemLoader: golden data was saved from originals,
// not generated by this extraction or by the processing code being checked.
function readRows($,config){
  const {itemConfig}=config;
  assert.equal($(itemConfig._listContainer).length,1);
  return $(itemConfig._listContainer).children(itemConfig._listItem).toArray().map(row=>
    Object.fromEntries(Object.entries(itemConfig).filter(([key])=>!key.startsWith('_')).map(([key,rule])=>{
      const [css,attr]=rule.split('::'),node=$(row).find(css).first();
      return [key,attr&&attr!=='text'?node.attr(attr)??'':node.text().trim()];
    })));
}

test('four ordered entries match capture grammar and remain bounded to the current page',()=>{
  assert.deepEqual(originalSites.map(({name,kind})=>[name,kind]),[
    ['fixtureDouban','fixture'],['fixtureCsdn','fixture'],['liveDouban','live'],['liveCsdn','live']]);
  for(const {config} of originalSites){
    assert.deepEqual(validateCapture(structuredClone(config)),config);
    assert.equal(config.maxPages,1);
    assert(!Object.hasOwn(config,'nextPageSelector'));
    assert(!Object.hasOwn(config,'detail'));
    assert.deepEqual(Object.keys(config.validation).sort(),['rowShape','version']);
    assert.equal(config.fieldRequirements.length,Object.keys(config.itemConfig).length-2);
  }
  assert.deepEqual(originalSites.slice(0,2).map(e=>e.config.url),[
    'http://127.0.0.1:43111/scrapyjs-fixtures/douban-books.html',
    'http://127.0.0.1:43111/scrapyjs-fixtures/csdn.html']);
  assert.deepEqual(originalSites.slice(2).map(e=>e.config.url),[expected.doubanBooks.url,expected.csdn.url]);
  for(const entry of originalSites.slice(2))assert(!Object.hasOwn(entry,'expectedData'),'live oracle must come from runtime DOM');
  assert.equal(originalSites[2].config.url,'https://book.douban.com/tag/%E7%BC%96%E7%A8%8B?start=0&type=T');
  assert.equal(originalSites[3].config.url,'https://download.csdn.net/list/blog/100-0-0-0-5-1.html');
  assert(originalSites.slice(0,2).every(e=>JSON.stringify(e.config).length<4096));
});

for(const [index,key,count] of [[0,'doubanBooks',20],[1,'csdn',9]]){
  test(`${key}: inert fixture retains every original field and stable source hash`,async()=>{
    const entry=originalSites[index],golden=expected[key];
    const bytes=await readFile(new URL(golden.fixture.path,root));
    assert.equal(sha(bytes),golden.fixture.sha256);
    const $=load(bytes.toString());
    assert.equal($('script,style,link,img,iframe,object,embed,video,audio,source').length,0);
    assert.match($('meta[http-equiv="Content-Security-Policy"]').attr('content'),/default-src 'none'/);
    $('*').each((_,el)=>{for(const attr of Object.keys(el.attribs))assert(!/^on|^(?:style|src|srcset|poster|background|action|formaction|ping)$/i.test(attr));});
    assert.equal($(entry.config.waitForSelector).length,count);
    const raw=readRows($,entry.config);
    assert.equal(raw.length,count);
    assert.deepEqual(entry.expectedData,golden.data);
    const actual=entry.config.processing?raw.map(row=>sdk.AIConfig.Processing.processRecord(row,entry.config.processing)):raw;
    assert.deepEqual(actual,golden.data);
    assert(actual.every(row=>Object.keys(row).length===(index===0?11:7)));
  });
}

