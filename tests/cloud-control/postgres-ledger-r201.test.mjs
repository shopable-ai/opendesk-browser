pgTest('unproven receipts cannot persist or release capacity through adapter or SQL', async t => {
  const {ledger, other, pool, ledgerId} = await fixture(t);
  await ledger.transaction(state => { state.jobs.job = {...job('job'), assignment:assignment('job'), cancelled:true}; });
  for (const retirementState of [undefined, null, 'pending', 'unknown', false]) {
    const unproven = receipt();
    if (retirementState === undefined) delete unproven.result.retirementState;
    else unproven.result.retirementState = retirementState;
    await assert.rejects(other.transaction(state => { state.jobs.job.receipt = unproven; }), {code:'E_RECEIPT_RETIREMENT'});
    await assert.rejects(pool.query('INSERT INTO opendesk_cc_receipts (ledger_id, key, body) VALUES ($1, $2, $3::jsonb)',
      [ledgerId, 'job', JSON.stringify(unproven)]), /E_RECEIPT_RETIREMENT/);
  }
  await assert.rejects(pool.query('UPDATE opendesk_cc_assignments SET dispatch_slot = NULL WHERE ledger_id = $1', [ledgerId]), /E_DISPATCH_SLOT/);
  assert.equal((await pool.query('SELECT dispatch_slot FROM opendesk_cc_assignments WHERE ledger_id = $1', [ledgerId])).rows[0].dispatch_slot, 'executor-1');
  assert.equal(await ledger.transaction(state => state.jobs.job.receipt, {readOnly:true}), undefined);
  await assert.rejects(other.transaction(state => { state.jobs.next = {...job('next'), assignment:assignment('next')}; }), {code:'E_EXECUTOR_CAPACITY'});
});

pgTest('initialize binds existing identity and invokes its pre-insert callback once with rollback on failure', async t => {
  let fresh, newId;
  // Register before fixture cleanup so this random child ledger is removed before Pool.end().
  t.after(async () => { await fresh?.close(); if (newId) await cleanupLedger(pool, newId); });
  const {ledger, pool, ledgerId, state} = await fixture(t);
  let called = 0;
  await ledger.initialize({requireExisting:true, expectedProviderId:state.providerId,
    beforeInitialize:async providerId => { called++; assert.equal(providerId, state.providerId); }});
  assert.equal(called, 1);
  await assert.rejects(ledger.initialize({expectedProviderId:'wrong', beforeInitialize:() => { called++; }}), {code:'E_LEDGER_IDENTITY'});
  assert.equal(called, 1);
  newId = `${ledgerId}:new`;
  fresh = await openPostgresLedger({pool, ledgerId:newId});
  await assert.rejects(fresh.initialize({state:seed(), credentials:credentials(), requireExisting:true,
    beforeInitialize:() => { called++; }}), {code:'E_LEDGER_RECOVERY_REQUIRED'});
  assert.equal(called, 1);
  const freshState = seed();
  await assert.rejects(fresh.initialize({state:freshState, credentials:credentials(), beforeInitialize:async providerId => {
    called++;
    assert.equal(providerId, freshState.providerId);
    assert.equal((await pool.query('SELECT 1 FROM opendesk_cc_ledgers WHERE ledger_id = $1', [newId])).rowCount, 0);
    throw new Error('marker durability failed');
  }}), /marker durability failed/);
  assert.equal(called, 2, 'failed callback is never automatically retried');
  assert.equal((await pool.query('SELECT 1 FROM opendesk_cc_ledgers WHERE ledger_id = $1', [newId])).rowCount, 0);
  const loaded = await fresh.initialize({state:freshState, credentials:credentials(), beforeInitialize:providerId => {
    called++; assert.equal(providerId, freshState.providerId);
  }});
  assert.equal(loaded.state.providerId, freshState.providerId);
  assert.equal(called, 3);
});
