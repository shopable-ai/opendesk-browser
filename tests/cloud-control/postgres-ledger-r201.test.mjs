test('all transaction statements use one client; rollback failure destroys it without retrying callback', async () => {
  const calls = [], rollbackError = new Error('rollback failed'), callbackError = new Error('callback failed');
  let released, callbacks = 0;
  const client = {
    async query(sql) {
      calls.push(sql);
      if (sql === 'ROLLBACK') throw rollbackError;
      if (sql.startsWith('SELECT metadata')) return {rows:[{metadata:{version:1, providerId:'provider'}, credentials:{}}]};
      return {rows:[]};
    },
    release(error) { released = error; }
  };
  const ledger = await openPostgresLedger({pool:{async connect() { return client; }}, ledgerId:'mock'});
  await assert.rejects(ledger.transaction(async () => { callbacks++; await Promise.resolve(); throw callbackError; }), error => error === callbackError);
  assert.equal(callbacks, 1);
  assert.equal(released, rollbackError);
  assert.equal(calls[0], 'BEGIN ISOLATION LEVEL READ COMMITTED');
  assert.equal(calls[1], 'SET LOCAL synchronous_commit = on');
  assert.match(calls[2], /pg_advisory_xact_lock/);
  assert.match(calls[2], /pg_advisory_xact_lock_shared/);
  assert.match(calls[3], /pg_advisory_xact_lock\(/);
  assert.equal(calls.at(-1), 'ROLLBACK');
  assert.ok(!calls.includes('COMMIT'));
});

