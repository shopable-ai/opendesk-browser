pgTest('independent Pools serialize claims; Stop/expiry do not release the dispatch slot', async t => {
  const {ledger, other} = await fixture(t);
  let unblock, entered;
  const gate = new Promise(resolve => { unblock = resolve; });
  const firstEntered = new Promise(resolve => { entered = resolve; });
  const first = ledger.transaction(async state => {
    state.jobs.first = {...job('first'), assignment:assignment('first')};
    entered(); await gate; return 'first';
  });
  await firstEntered;
  let secondCalled = false;
  const second = other.transaction(state => {
    secondCalled = true;
    assert.ok(state.jobs.first, 'callback reads the first committed state after lock acquisition');
    state.jobs.second = {...job('second'), assignment:assignment('second')};
  });
  // Let the second connection attempt its lock while the first callback is suspended.
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal(secondCalled, false);
  unblock();
  assert.equal(await first, 'first');
  await assert.rejects(second, {code:'E_EXECUTOR_CAPACITY'});
  await ledger.transaction(state => { state.jobs.first.cancelled = true; state.jobs.first.assignment.leaseUntil = -1; });
  await assert.rejects(other.transaction(state => { state.jobs.second = {...job('second'), assignment:assignment('second')}; }), {code:'E_EXECUTOR_CAPACITY'});
  await ledger.transaction(state => {
    state.jobs.first.receipt = receipt();
    state.jobs.second = {...job('second'), assignment:assignment('second')};
  });
  assert.ok((await other.transaction(state => state.jobs.second, {readOnly:true})).assignment);
});

