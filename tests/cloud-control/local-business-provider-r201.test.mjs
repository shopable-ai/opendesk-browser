// Cascading fixture deletion participates in the adapter's DDL -> ledger order.
// IDs are generated by this test only; never remove shared or historical data.
async function cleanupLedger(pool, ledgerId) {
  const client = await pool.connect();
  let destroy;
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock_shared(hashtextextended($1, 0))', ['opendesk:cloud:ddl:r201']);
    await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1, 0))', [`opendesk:cloud:ledger:${ledgerId}`]);
    await client.query('DELETE FROM opendesk_cc_ledgers WHERE ledger_id = $1', [ledgerId]);
    await client.query('COMMIT');
  } catch (error) {
    try { await client.query('ROLLBACK'); } catch (rollbackError) { destroy = rollbackError; }
    throw error;
  } finally { client.release(destroy); }
}

function providerPost(provider, path, input, credential, ca) {
  return new Promise((resolve, reject) => {
    const bytes = Buffer.from(JSON.stringify(input));
    const req = (ca ? https : http).request({hostname:'127.0.0.1',
      port:ca ? provider.publicPort : provider.port, path, method:'POST',
      ...(ca ? {ca, rejectUnauthorized:true} : {}),
      headers:{'content-type':'application/json', 'content-length':bytes.length,
        ...(credential ? {authorization:`Bearer ${credential}`} : {})}}, res => {
      const chunks = [];
      res.on('data', chunk => chunks.push(chunk));
      res.on('error', reject);
      res.on('end', () => {
        try { resolve({status:res.statusCode, value:JSON.parse(Buffer.concat(chunks).toString('utf8'))}); }
        catch (error) { reject(error); }
      });
    });
    req.setTimeout(8000, () => req.destroy(new Error('test Provider request timeout')));
    req.on('error', reject);
    req.end(bytes);
  });
}

function browser(origin) {
  let cookie, csrf;
  return {
    async request(path, input, overrides = {}) {
      const res = await fetch(origin + path, {method:input === undefined ? 'GET' : 'POST',
        headers:{...(cookie ? {cookie} : {}), ...(input === undefined ? {} : {
          origin, 'content-type':'application/json', 'x-csrf-token':csrf}), ...overrides},
        ...(input === undefined ? {} : {body:JSON.stringify(input)}),
        redirect:'error', signal:AbortSignal.timeout(10000)});
      const setCookie = res.headers.get('set-cookie');
      if (setCookie) cookie = setCookie.split(';')[0];
      const value = await res.json();
      if (value.csrf) csrf = value.csrf;
      return {status:res.status, value, setCookie};
    },
    async login(account) {
      const initial = await this.request('/api/session');
      assert.equal(initial.status, 200);
      assert.match(initial.setCookie, /HttpOnly; SameSite=Strict/);
      const result = await this.request('/api/login', {username:account.username, password:account.password});
      assert.equal(result.status, 200);
      assert.equal(result.value.username, account.username);
      assert.notEqual(result.setCookie, initial.setCookie, 'login rotates the anonymous session');
      assert.notEqual(result.value.csrf, initial.value.csrf);
    }
  };
}

async function fixedTask(operation, recordsOrigin) {
  const source = `async function main() {
    await page.type('#${operation}-recordKey', params.recordKey);
    await page.type('#${operation}-name', params.name);
    await page.type('#${operation}-status', params.status);
    await page.click('#${operation}-submit');
    await page.waitForSelector('#${operation}-result');
  }`;
  return createTaskPackage({format:'opendesk.task.v1', taskId:`local-business.${operation}`,
    version:'1.0.0', title:`Local records ${operation}`, description:'Fixed local integration fixture',
    author:'OpenDesk test', source:'local-test', siteOrigins:[recordsOrigin],
    permissions:['page.automation'], entryFormat:'async-main',
    program:{revision:1, sourceHash:await digestUtf8(source)},
    paramsSchema:{type:'object', properties:{
      recordKey:{type:'string', title:'Record key', minLength:1, maxLength:150},
      name:{type:'string', title:'Name', minLength:1, maxLength:200},
      status:{type:'string', title:'Status', minLength:1, maxLength:80}},
    required:['recordKey','name','status'], additionalProperties:false}}, source);
}

// Backend integration only: no Browser/Chrome Task execution or native receipt is claimed.
test('R20.1 real PG + TLS Provider + business BFF: scoped catalog, stable jobs, refresh and Stop', {
  skip:!databaseUrl && 'Provide CLOUD_CONTROL_TEST_DATABASE_URL or .local/cloud-r201/environment.json; real PostgreSQL required',
  timeout:60000
}, async t => {
  const {Pool} = require('pg');
  const pool = new Pool({connectionString:databaseUrl, max:4, connectionTimeoutMillis:5000});
  const directory = await mkdtemp(join(tmpdir(), 'od-business-provider-'));
  const ledgerId = 'business-provider-test:' + randomUUID();
  const businessId = 'business-provider-test:' + randomUUID();
  let provider, app, reservation, proxy;
  let dropSubmitResponse = true;
  t.after(async () => {
    try {
      await app?.close();
      if (proxy) { proxy.closeAllConnections(); await new Promise(resolve => proxy.close(resolve)); }
      await provider?.close();
      if (reservation?.listening) await new Promise(resolve => reservation.close(resolve));
    } finally {
      try {
        for (const table of ['opendesk_local_business_records', 'opendesk_local_business_requests']) {
          const exists = await pool.query('SELECT to_regclass($1) AS relation', [table]);
          if (exists.rows[0].relation) await pool.query(`DELETE FROM ${table} WHERE business_id=$1`, [businessId]);
        }
        await cleanupLedger(pool, ledgerId);
      } finally {
        await pool.end();
        await rm(directory, {recursive:true, force:true});
      }
    }
  });

  const ledger = await openPostgresLedger({pool, ledgerId});
  const keyFile = join(directory, 'tls.key'), certFile = join(directory, 'tls.crt');
  execFileSync('openssl', ['req','-x509','-newkey','rsa:2048','-nodes','-keyout',keyFile,
    '-out',certFile,'-days','1','-subj','/CN=127.0.0.1','-addext','subjectAltName=IP:127.0.0.1'], {stdio:'ignore'});
  const ca = await readFile(certFile);
  provider = await openProvider({directory, port:0, ledger,
    publicTls:{port:0, host:'127.0.0.1', keyFile, certFile}});
  // A real TLS hop loses one successful submit response, reproducing an unknown
  // transport outcome without touching Provider/ledger implementation.
  proxy = https.createServer({key:await readFile(keyFile), cert:ca}, async (req, res) => {
    const chunks = [];
    for await (const chunk of req) chunks.push(chunk);
    const input = JSON.parse(Buffer.concat(chunks).toString());
    if (req.url === '/v1/submit') {
      const persisted = await pool.query(`SELECT execution_key FROM opendesk_local_business_requests
        WHERE business_id=$1 AND execution_key=$2`, [businessId, new URL(input.target.url).searchParams.get('executionKey')]);
      assert.equal(persisted.rowCount, 1, 'intent/token committed before Provider submit');
    }
    const result = await providerPost(provider, req.url, input, req.headers.authorization?.slice(7), ca);
    if (req.url === '/v1/submit' && dropSubmitResponse) {
      dropSubmitResponse = false;
      // Exceed the BFF's total deadline after Provider accepted the request.
      return;
    }
    res.writeHead(result.status, {'content-type':'application/json'});
    res.end(JSON.stringify(result.value));
  });
  await new Promise(resolve => proxy.listen(0, '127.0.0.1', resolve));
  const admin = JSON.parse(await readFile(provider.credentialFile, 'utf8'));
  const local = async (path, input, credential = admin.adminToken) => {
    const result = await providerPost(provider, path, input, credential);
    assert.equal(result.status, 200, `${path}: ${JSON.stringify(result.value)}`);
    return result.value;
  };
  const remote = (path, input, credential) => providerPost(provider, path, input, credential, ca);

  // Obtain an OS-assigned records port before freezing its exact origin. Bind the
  // BFF to that same port and fail rather than silently accepting another origin.
  reservation = net.createServer();
  await new Promise((resolve, reject) => {
    reservation.once('error', reject);
    reservation.listen(0, '127.0.0.1', resolve);
  });
  const recordsPort = reservation.address().port;
  const recordsOrigin = `http://127.0.0.1:${recordsPort}`;
  const packages = await Promise.all(['create','update'].map(op => fixedTask(op, recordsOrigin)));
  const pins = await Promise.all(packages.map(async pkg => {
    const registered = await registeredPackage(pkg);
    await local('/admin/register', {manifest:pkg.manifest, manifestHash:pkg.manifestHash});
    return taskPin(registered);
  }));
  const executorId = randomUUID(), grantId = randomUUID();
  const paired = await local('/v1/pair', {executorId, pairingCode:admin.pairingCode});
  await local('/v1/capabilities', {grantId, tasks:pins}, paired.credential);
  const clients = [];
  for (const label of ['alice','bob']) clients.push(await local('/v1/client-grant',
    {grantId, tasks:pins, allowResult:false, label}, paired.credential));
  assert.notEqual(clients[0].credential, clients[1].credential);
  const accounts = clients.map((client, i) => ({username:i ? 'bob' : 'alice',
    password:randomUUID(), tenantId:`tenant-${i}`, subjectId:`subject-${i}`,
    clientCredential:client.credential}));
  await new Promise(resolve => reservation.close(resolve));
  app = await openLocalBusiness({pool, businessId, recordsPort, accounts,
    providerUrl:`https://127.0.0.1:${proxy.address().port}`, providerCa:ca,
    taskActions:{'local-business.create':'create', 'local-business.update':'update'}});
  assert.equal(app.recordsOrigin, recordsOrigin);
  const alice = browser(app.portalOrigin), bob = browser(app.portalOrigin);
  assert.equal((await alice.request('/api/catalog')).status, 401);
  await alice.login(accounts[0]);
  await bob.login(accounts[1]);

  for (const [index, user] of [alice, bob].entries()) {
    const scope = await remote('/v1/client-scope', {includeTaskSchemas:true}, clients[index].credential);
    assert.equal(scope.status, 200);
    assert.equal(scope.value.clientId, clients[index].clientId);
    assert.deepEqual(scope.value.tasks, pins);
    assert.deepEqual(scope.value.taskCatalog.map(task => task.siteOrigins), [[recordsOrigin],[recordsOrigin]]);
    const catalog = await user.request('/api/catalog');
    assert.equal(catalog.status, 200);
    assert.equal(catalog.value.target, app.recordsUrl);
    assert.deepEqual(catalog.value.tasks, packages.map((pkg, i) => ({...pins[i],
      title:pkg.manifest.title, paramsSchema:pkg.manifest.paramsSchema})));
    for (const secret of [admin.adminToken, paired.credential, ...clients.map(c => c.credential), ...packages.map(p => p.sourceUtf8)]) {
      assert.ok(!JSON.stringify(catalog.value).includes(secret), 'catalog must not expose credentials or source');
    }
  }
  const input = {requestKey:'stable-business-key', taskId:pins[0].taskId, version:pins[0].version,
    params:{recordKey:'invoice-1', name:'真实后端集成', status:'draft'}};
  assert.equal((await alice.request('/api/submit', input, {'x-csrf-token':'wrong'})).status, 403);
  assert.equal((await alice.request('/api/submit', input, {origin:app.recordsOrigin})).status, 403);
  for (const [field, value] of Object.entries({source:'evil()', sourceUtf8:'evil()', script:'evil()',
    cdp:{method:'Runtime.evaluate'}, CDP:{method:'Runtime.evaluate'},
    target:{mode:'owned', url:'https://example.com/'}, executionKey:'f'.repeat(64), subjectId:'bob', tenantId:'evil'})) {
    const denied = await alice.request('/api/submit', {...input, [field]:value});
    assert.equal(denied.status, 400, `reject top-level ${field}`);
    assert.equal(denied.value.error.code, 'E_SCHEMA');
    assert.equal((await alice.request('/api/submit', {...input, params:{...input.params, [field]:value}})).status, 400,
      `reject param ${field}`);
  }
  assert.equal((await alice.request('/api/submit', {...input,taskId:'not-mapped'})).status, 403);
  for (const params of [{recordKey:'r',name:12,status:'s'}, {recordKey:'r',name:'n'},
    {...input.params,status:' '.repeat(2)}, {...input.params,name:'n'.repeat(201)}]) {
    assert.equal((await alice.request('/api/submit', {...input,params})).status, 400);
  }
  assert.deepEqual((await alice.request('/api/jobs')).value.jobs, []);
  const unknown = await alice.request('/api/submit', input);
  assert.equal(unknown.status, 502);
  const storedRequest = async () => (await pool.query(`SELECT execution_key, input, job_id
    FROM opendesk_local_business_requests WHERE business_id=$1 AND tenant_id=$2 AND subject_id=$3 AND request_key=$4`,
    [businessId,accounts[0].tenantId,accounts[0].subjectId,input.requestKey])).rows[0];
  const beforeRetry = await storedRequest();
  assert.match(beforeRetry.execution_key, /^[a-f0-9]{64}$/);
  assert.equal(beforeRetry.job_id, null);
  assert.equal((await alice.request('/api/submit', {...input, params:{...input.params,name:'changed-after-timeout'}})).status, 409);
  const first = await alice.request('/api/submit', input);
  assert.equal(first.status, 200, JSON.stringify(first.value));
  assert.ok(first.value.jobId);
  assert.equal(first.value.requestKey, input.requestKey);
  const retries = await Promise.all([alice.request('/api/submit', input), alice.request('/api/submit', {...input,params:{status:input.params.status,name:input.params.name,recordKey:input.params.recordKey}})]);
  for (const retry of retries) { assert.equal(retry.status, 200); assert.deepEqual(retry.value, first.value); }
  const afterRetry = await storedRequest();
  assert.equal(afterRetry.execution_key, beforeRetry.execution_key, 'retry reuses persisted token');
  assert.deepEqual(afterRetry.input, beforeRetry.input);
  const conflict = await alice.request('/api/submit', {...input, params:{...input.params, name:'changed'}});
  assert.equal(conflict.status, 409);
  assert.equal(conflict.value.error.code, 'E_REQUEST_CONFLICT');
  const otherTaskConflict = await alice.request('/api/submit', {...input, taskId:pins[1].taskId});
  assert.equal(otherTaskConflict.status, 409);
  const second = await alice.request('/api/submit', {...input, requestKey:'update-business-key', taskId:pins[1].taskId});
  assert.equal(second.status, 200);
  assert.notEqual(second.value.jobId, first.value.jobId);
  // Identical business key/input under another tenant/subject has a different
  // Provider client and must create an independent job.
  const other = await bob.request('/api/submit', input);
  assert.equal(other.status, 200);
  assert.notEqual(other.value.jobId, first.value.jobId);
  for (const [user, foreignJob, credential] of [[bob, first.value.jobId, clients[1].credential],
    [alice, other.value.jobId, clients[0].credential]]) {
    for (const route of ['job-status','job-cancel']) {
      const denied = await user.request(`/api/${route}`, {jobId:foreignJob});
      assert.equal(denied.status, 404);
      assert.equal(denied.value.error.code, 'E_JOB_NOT_FOUND');
      const direct = await remote(`/v1/${route}`, {jobId:foreignJob}, credential);
      assert.equal(direct.status, 400);
      assert.equal(direct.value.error.code, 'E_JOB');
    }
  }
  const refreshed = browser(app.portalOrigin);
  await refreshed.login(accounts[0]);
  const jobs = await refreshed.request('/api/jobs');
  assert.equal(jobs.status, 200);
  assert.deepEqual(jobs.value.jobs, [first.value, second.value]);
  assert.deepEqual((await bob.request('/api/jobs')).value.jobs, [other.value]);
  const status = await refreshed.request('/api/job-status', {jobId:first.value.jobId});
  assert.equal(status.status, 200);
  assert.deepEqual(status.value, {jobId:first.value.jobId, state:'queued', receiptConfirmed:false});
  assert.equal((await refreshed.request('/api/job-cancel', {jobId:first.value.jobId}, {'x-csrf-token':'wrong'})).status, 403);
  const stopped = await refreshed.request('/api/job-cancel', {jobId:first.value.jobId});
  assert.equal(stopped.status, 200);
  assert.deepEqual(stopped.value, {jobId:first.value.jobId, cancelled:true, alreadyFinished:false});
  const afterStop = await refreshed.request('/api/job-status', {jobId:first.value.jobId});
  assert.equal(afterStop.status, 200);
  assert.deepEqual(afterStop.value, {jobId:first.value.jobId, state:'cancelled', receiptConfirmed:false});
  assert.deepEqual((await refreshed.request('/api/submit', input)).value, first.value, 'retry after Stop must not replay');
  const state = await local('/admin/state', {});
  assert.equal(Object.keys(state.jobs).length, 3, 'retries, conflicts and rejected inputs never create extra Provider jobs');
  for (const [jobId, pin, client] of [[first.value.jobId,pins[0],clients[0]],
    [second.value.jobId,pins[1],clients[0]], [other.value.jobId,pins[0],clients[1]]]) {
    assert.deepEqual(state.jobs[jobId].task, pin);
    const target = new URL(state.jobs[jobId].target.url);
    assert.equal(target.origin + target.pathname, app.recordsUrl);
    assert.equal(state.jobs[jobId].target.mode, 'owned');
    const stored = (await pool.query(`SELECT execution_key FROM opendesk_local_business_requests
      WHERE business_id=$1 AND job_id=$2`, [businessId,jobId])).rows[0];
    assert.equal(target.searchParams.get('executionKey'), stored.execution_key);
    assert.equal(state.jobs[jobId].submittedBy, client.clientId);
  }
  const recordsAlice = browser(app.recordsOrigin), recordsBob = browser(app.recordsOrigin);
  await recordsAlice.login(accounts[0]); await recordsBob.login(accounts[1]);
  const executionKey = beforeRetry.execution_key;
  const contextPath = '/api/execution?executionKey=' + executionKey;
  assert.equal((await recordsBob.request(contextPath)).status, 403);
  const context = await recordsAlice.request(contextPath);
  assert.deepEqual(context.value, {action:'create',params:input.params});
  const bound = {...input.params, executionKey};
  assert.equal((await recordsBob.request('/api/records/create', bound)).status, 403);
  assert.equal((await recordsAlice.request('/api/records/update', bound)).status, 403);
  assert.equal((await recordsAlice.request('/api/records/create', {...bound,name:'tampered'})).status, 403);
  assert.equal((await recordsAlice.request('/api/records/create', {...bound,executionKey:'invalid'})).status, 400);
  assert.equal((await recordsAlice.request(contextPath + '&executionKey=' + executionKey)).status, 400);
  assert.equal((await recordsAlice.request('/api/records/create', bound)).status, 200);
  assert.deepEqual((await recordsBob.request('/api/records?recordKey=invoice-1')).value.records, []);
  // Same browser has verified Alice, then logs into Bob before POST: server
  // rechecks the current cookie scope rather than trusting prior UI readiness.
  await recordsAlice.request('/api/login', {username:accounts[1].username,password:accounts[1].password});
  assert.equal((await recordsAlice.request('/api/records/create', bound)).status, 403);
  const updateKey = new URL(state.jobs[second.value.jobId].target.url).searchParams.get('executionKey');
  await recordsAlice.request('/api/login', {username:accounts[0].username,password:accounts[0].password});
  assert.equal((await recordsAlice.request('/api/records/create', {...input.params,executionKey:updateKey})).status, 403);
  assert.equal((await recordsAlice.request('/api/records/update', {...input.params,executionKey:updateKey})).status, 200);
  const readback = (await recordsAlice.request('/api/records?recordKey=invoice-1')).value.records;
  assert.equal(readback.length, 1);
  assert.equal(readback[0].name, input.params.name);
  assert.equal(readback[0].status, input.params.status);
  assert.equal((await bob.request('/api/job-status', {jobId:other.value.jobId})).value.state, 'queued');
  const persisted = await pool.query('SELECT count(*)::int AS count FROM opendesk_cc_jobs WHERE ledger_id=$1', [ledgerId]);
  assert.equal(persisted.rows[0].count, 3);
});
