// Cascading fixture deletion participates in the adapter's DDL -> ledger order.
// IDs are generated by this test only; never remove shared or historical data.
async function cleanupLedger(pool, ledgerId) {
  const client = await pool.connect();
  let destroy;
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock_shared(hashtextextended($1, 0))', ['opendesk:cloud:ddl:r201']);
    await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1, 0))', [`opendesk:cloud:ledger:${ledgerId}`]);
    await client.query('DELETE FROM opendesk_cc_ledgers WHERE ledger_id = $1', [ledgerId]);
    await client.query('COMMIT');
  } catch (error) {
    try { await client.query('ROLLBACK'); } catch (rollbackError) { destroy = rollbackError; }
    throw error;
  } finally { client.release(destroy); }
}

function post(provider,path,body,credential,ca){
  return new Promise((resolve,reject)=>{
    const payload=Buffer.from(JSON.stringify(body));
    const request=(ca?https:require('node:http')).request({hostname:'127.0.0.1',
      port:ca?provider.publicPort:provider.port,path,method:'POST',...(ca?{ca}:{}),
      headers:{'Content-Type':'application/json','Content-Length':payload.length,
        ...(credential?{Authorization:'Bearer '+credential}:{})}},response=>{
      const chunks=[];response.on('data',chunk=>chunks.push(chunk));
      response.on('end',()=>{try{
        const answer=JSON.parse(Buffer.concat(chunks));
        if(response.statusCode!==200)reject(Object.assign(Error(answer.error?.message),{code:answer.error?.code}));
        else resolve(answer);
      }catch(error){reject(error);}});
    });request.on('error',reject);request.end(payload);
  });
}

test('R20.1 real PostgreSQL: two Provider instances share Claim/capacity, sessions, Outbox and immutable receipts',
  {skip:!url&&'CLOUD_CONTROL_TEST_DATABASE_URL is required; no database PASS without PostgreSQL',timeout:30000},async t=>{
    const {Pool}=require('pg'),directory=await mkdtemp(join(tmpdir(),'od-pg-provider-'));
    const pools=[new Pool({connectionString:url}),new Pool({connectionString:url})];
    const ledgerId='provider-test:'+randomUUID();
    const ledgers=await Promise.all(pools.map(pool=>openPostgresLedger({pool,ledgerId})));
    const keyFile=join(directory,'tls.key'),certFile=join(directory,'tls.crt');
    execFileSync('openssl',['req','-x509','-newkey','rsa:2048','-nodes','-keyout',keyFile,
      '-out',certFile,'-days','1','-subj','/CN=127.0.0.1','-addext','subjectAltName=IP:127.0.0.1'],{stdio:'ignore'});
    const ca=await readFile(certFile),publicTls={port:0,host:'127.0.0.1',keyFile,certFile};
    let now=Date.now(),a,b,ws;
    t.after(async()=>{
      ws?.terminate();await a?.close();await b?.close();
      await cleanupLedger(pools[0],ledgerId);
      await Promise.all(pools.map(pool=>pool.end()));await rm(directory,{recursive:true,force:true});
    });
    const open=(index,name)=>openProvider({directory:join(directory,name),port:0,publicTls,
      clock:()=>now,ledger:ledgers[index]});
    a=await open(0,'a');b=await open(1,'b');
    assert.equal(a.providerId,b.providerId);
    await assert.rejects(readFile(join(a.directory,'state.json')),{code:'ENOENT'});
    const admin=JSON.parse(await readFile(a.credentialFile,'utf8'));
    assert.deepEqual(JSON.parse(await readFile(b.credentialFile,'utf8')),admin);
    const executorId=randomUUID(),grantId=randomUUID();
    const pair=await post(a,'/v1/pair',{executorId,pairingCode:admin.pairingCode});
    await post(b,'/v1/capabilities',{grantId,tasks:[pin]},pair.credential);
    // Ticket issued on A is consumed on B. It remains a transport proof only.
    const auth=await post(a,'/v1/auth',{},pair.credential);
    ws=new WebSocket('ws://127.0.0.1:'+b.port+'/v1/events');
    await new Promise((resolve,reject)=>{
      ws.once('open',()=>ws.send(JSON.stringify({type:'authenticate',ticket:auth.ticket})));
      ws.once('message',data=>{try{assert.equal(JSON.parse(String(data)).type,'authenticated');resolve();}catch(error){reject(error);}});
      ws.once('error',reject);
    });
    const client=await post(a,'/v1/client-grant',{grantId,tasks:[pin],allowResult:false,label:'R20 local test'},pair.credential);
    const submit={requestKey:'stable-key',...pin,params:{},target:{mode:'owned',url:'http://127.0.0.1:43111/demo-form.html'}};
    const notice=new Promise((resolve,reject)=>{
      const timeout=setTimeout(()=>reject(Error('Outbox did not relay to other Provider')),5000);
      const listener=data=>{const message=JSON.parse(String(data));if(message.type==='notify'&&message.offer?.jobId){
        clearTimeout(timeout);ws.off('message',listener);resolve(message);
      }};ws.on('message',listener);
    });
    const first=await post(a,'/v1/submit',submit,client.credential,ca);
    assert.deepEqual(await post(b,'/v1/submit',submit,client.credential,ca),first);
    await assert.rejects(post(b,'/v1/submit',{...submit,params:{name:'different'}},client.credential,ca),{code:'E_REQUEST_CONFLICT'});
    const offered=await notice;
    assert.equal(offered.offer.jobId,first.jobId);
    assert.deepEqual(Object.keys(offered.offer),['jobId']);
    const second=await post(b,'/v1/submit',{...submit,requestKey:'second'},client.credential,ca);
    const ready=await post(a,'/v1/pull-open',{grantId,tasks:[pin]},pair.credential);
    ws.terminate();
    const claim=claimId=>({claimId,grantId,tasks:[pin],pullSessionId:ready.sessionId});
    const raced=await Promise.all([post(a,'/v1/claim',claim('race-a'),pair.credential),post(b,'/v1/claim',claim('race-b'),pair.credential)]);
    const assignments=raced.map(answer=>answer.assignment).filter(Boolean);
    assert.equal(assignments.length,1,'Claim and capacity reserve atomically across instances');
    const assignment=assignments[0];
    assert.ok([first.jobId,second.jobId].includes(assignment.jobId));
    const binding=Object.fromEntries(bindingKeys.map(key=>[key,assignment[key]]));
    const runRef={runId:randomUUID(),resultId:randomUUID(),requestId:'cloud:'+assignment.assignmentId,
      sourceHash:pin.sourceHash,manifestHash:pin.manifestHash,grantId};
    const permit=await post(b,'/v1/admission',{assignmentId:assignment.assignmentId,runRef,resultAllowed:false,binding},pair.credential);
    now+=90001;
    await assert.rejects(post(a,'/v1/renew',{assignmentId:assignment.assignmentId,permitId:permit.permitId,binding},pair.credential),{code:'E_LEASE'});
    const fresh=await post(b,'/v1/pull-open',{grantId,tasks:[pin]},pair.credential);
    assert.deepEqual(await post(a,'/v1/claim',{...claim('expired-no-replay'),pullSessionId:fresh.sessionId},pair.credential),{assignment:null});
    await post(a,'/v1/job-cancel',{jobId:assignment.jobId},client.credential,ca);
    assert.deepEqual(await post(b,'/v1/claim',{...claim('stopped-no-release'),pullSessionId:fresh.sessionId},pair.credential),{assignment:null});
    const status=await post(b,'/v1/job-status',{jobId:assignment.jobId},client.credential,ca);
    assert.equal(status.state,'OUTCOME_UNKNOWN');
    const receipt={assignmentId:assignment.assignmentId,receiptKey:runRef.resultId,runRef,binding,
      result:{visibility:'status-only',state:'stopped',retirementState:'released'}};
    const unproven={...receipt,result:{visibility:'status-only',state:'stopped'}};
    for(const provider of [a,b])await assert.rejects(post(provider,'/v1/receipt',unproven,pair.credential),{code:'E_RESULT_SCOPE'});
    assert.deepEqual(await post(b,'/v1/claim',{...claim('unproven-still-occupied'),pullSessionId:fresh.sessionId},pair.credential),{assignment:null});
    assert.equal((await pools[0].query('SELECT count(*)::int AS count FROM opendesk_cc_assignments WHERE ledger_id=$1 AND dispatch_slot IS NOT NULL',[ledgerId])).rows[0].count,1);
    assert.equal((await pools[0].query('SELECT count(*)::int AS count FROM opendesk_cc_receipts WHERE ledger_id=$1',[ledgerId])).rows[0].count,0);
    await post(a,'/admin/fault',{path:'/v1/receipt',count:1},admin.adminToken);
    await assert.rejects(post(b,'/v1/receipt',receipt,pair.credential));
    const ack=await post(a,'/v1/receipt',receipt,pair.credential);
    assert.deepEqual(await post(b,'/v1/receipt',receipt,pair.credential),ack);
    await assert.rejects(post(b,'/v1/receipt',{...receipt,result:{...receipt.result,state:'completed'}},pair.credential),{code:'E_REQUEST_CONFLICT'});
    const next=await post(b,'/v1/claim',{...claim('after-settlement'),pullSessionId:fresh.sessionId},pair.credential);
    assert.ok(next.assignment);
    assert.notEqual(next.assignment.jobId,assignment.jobId);
    await a.close();a=null;a=await open(0,'a');
    assert.deepEqual(await post(a,'/v1/receipt',receipt,pair.credential),ack);
    const reconciled=await post(a,'/v1/reconcile',{},pair.credential);
    assert.equal(reconciled.assignments.find(row=>row.jobId===assignment.jobId).receipt.receiptId,ack.receiptId);
    await assert.rejects(openProvider({directory:a.directory,port:0}),{code:'E_PROVIDER_BUSY'});
    await a.close();a=null;
    await assert.rejects(openProvider({directory:join(directory,'a'),port:0}),{code:'E_LEDGER_REQUIRED'});
    const {rows}=await pools[0].query('SELECT count(*)::int AS count FROM opendesk_cc_assignments WHERE ledger_id=$1 AND dispatch_slot IS NOT NULL',[ledgerId]);
    assert.equal(rows[0].count,1);
  });

test('R20.1 real PostgreSQL: marker rejects a missing ledger or same ledgerId with different provider identity',
  {skip:!url,timeout:30000},async t=>{
    const {Pool}=require('pg'),directory=await mkdtemp(join(tmpdir(),'od-pg-identity-'));
    const control=new Pool({connectionString:url});
    const schemas=Array.from({length:3},()=>`r201_${randomUUID().replaceAll('-','')}`);
    const pools=[],providers=[];
    const ledgerId='identity-test:'+randomUUID();
    t.after(async()=>{
      for(const provider of providers)await provider.close();
      await Promise.all(pools.map(pool=>pool.end()));
      for(const schema of schemas)await control.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      await control.end();await rm(directory,{recursive:true,force:true});
    });
    for(const schema of schemas){
      await control.query(`CREATE SCHEMA ${schema}`);
      pools.push(new Pool({connectionString:url,options:`-c search_path=${schema}`}));
    }
    const ledgers=await Promise.all(pools.map(pool=>openPostgresLedger({pool,ledgerId})));
    t.after(async()=>{for(const ledger of ledgers)await ledger.close();});
    const originalDirectory=join(directory,'original');
    const first=await openProvider({directory:originalDirectory,port:0,ledger:ledgers[0]});
    const providerId=first.providerId;await first.close();
    const marker=await readFile(join(originalDirectory,'ledger.json'),'utf8');
    assert.deepEqual(JSON.parse(marker),{format:'opendesk.cloud-ledger.v1',ledgerId,providerId});
    // An empty schema models connecting the saved directory to the wrong database.
    await assert.rejects(openProvider({directory:originalDirectory,port:0,ledger:ledgers[1]}),{code:'E_LEDGER_RECOVERY_REQUIRED'});
    assert.equal((await pools[1].query("SELECT to_regclass('opendesk_cc_ledgers') AS relation")).rows[0].relation,null);
    const different=await openProvider({directory:join(directory,'different'),port:0,ledger:ledgers[2]});
    assert.notEqual(different.providerId,providerId);await different.close();
    await assert.rejects(openProvider({directory:originalDirectory,port:0,ledger:ledgers[2]}),{code:'E_LEDGER_IDENTITY'});
    assert.equal(await readFile(join(originalDirectory,'ledger.json'),'utf8'),marker);
    await assert.rejects(openProvider({directory:originalDirectory,port:0}),{code:'E_LEDGER_REQUIRED'});
    // Each failure released the directory lock; the correct DB can reopen it.
    const restored=await openProvider({directory:originalDirectory,port:0,ledger:ledgers[0]});providers.push(restored);
    assert.equal(restored.providerId,providerId);
    const adopted=await openProvider({directory:join(directory,'adopted'),port:0,ledger:ledgers[0]});providers.push(adopted);
    assert.equal(adopted.providerId,providerId);
    assert.deepEqual(JSON.parse(await readFile(join(adopted.directory,'ledger.json'),'utf8')),JSON.parse(marker));
  });

test('R20.1 real PostgreSQL: first initialize failure retains pre-insert marker and fails closed on retry',
  {skip:!url,timeout:30000},async t=>{
    const {Pool}=require('pg'),directory=await mkdtemp(join(tmpdir(),'od-pg-startup-'));
    const pool=new Pool({connectionString:url});
    const ledgerId='startup-test:'+randomUUID();
    let insertAttempts=0,ledger,retry;
    t.after(async()=>{
      await ledger?.close();await retry?.close();
      await cleanupLedger(pool,ledgerId);
      await pool.end();await rm(directory,{recursive:true,force:true});
    });
    ledger=await openPostgresLedger({ledgerId,pool:{async connect(){
      const client=await pool.connect();
      return {async query(sql,args){
        if(sql.startsWith('INSERT INTO opendesk_cc_ledgers')){
          insertAttempts++;
          // Marker is already complete and visible before the first business row.
          const marker=JSON.parse(await readFile(join(directory,'ledger.json'),'utf8'));
          assert.equal(marker.ledgerId,ledgerId);
          assert.equal(marker.providerId,JSON.parse(args[1]).providerId);
          throw new Error('injected first ledger insert failure');
        }
        return client.query(sql,args);
      },release(error){client.release(error);}};
    }}});
    await assert.rejects(openProvider({directory,port:0,ledger}),/injected first ledger insert failure/);
    assert.equal(insertAttempts,1);
    const marker=await readFile(join(directory,'ledger.json'),'utf8');
    assert.equal((await pool.query('SELECT 1 FROM opendesk_cc_ledgers WHERE ledger_id=$1',[ledgerId])).rowCount,0);
    await assert.rejects(readFile(join(directory,'provider.lock')),{code:'ENOENT'});
    await assert.rejects(openProvider({directory,port:0}),{code:'E_LEDGER_REQUIRED'});
    retry=await openPostgresLedger({pool,ledgerId});
    for(let attempt=0;attempt<2;attempt++){
      await assert.rejects(openProvider({directory,port:0,ledger:retry}),{code:'E_LEDGER_RECOVERY_REQUIRED'});
      await assert.rejects(readFile(join(directory,'provider.lock')),{code:'ENOENT'});
    }
    assert.equal(await readFile(join(directory,'ledger.json'),'utf8'),marker);
    await assert.rejects(readFile(join(directory,'state.json')),{code:'ENOENT'});
  });

test('R20.1 real PostgreSQL: marker callback failure rolls back and releases directory lock for a clean retry',
  {skip:!url,timeout:30000},async t=>{
    const {Pool}=require('pg'),directory=await mkdtemp(join(tmpdir(),'od-pg-marker-'));
    const pool=new Pool({connectionString:url}),ledgerId='marker-test:'+randomUUID();
    const ledger=await openPostgresLedger({pool,ledgerId});
    let provider;
    t.after(async()=>{
      await provider?.close();await ledger.close();
      await cleanupLedger(pool,ledgerId);
      await pool.end();await rm(directory,{recursive:true,force:true});
    });
    await mkdir(join(directory,'ledger.json.tmp'));
    await assert.rejects(openProvider({directory,port:0,ledger}),{code:'EISDIR'});
    assert.equal((await pool.query('SELECT 1 FROM opendesk_cc_ledgers WHERE ledger_id=$1',[ledgerId])).rowCount,0);
    await assert.rejects(readFile(join(directory,'provider.lock')),{code:'ENOENT'});
    await assert.rejects(readFile(join(directory,'ledger.json')),{code:'ENOENT'});
    await rm(join(directory,'ledger.json.tmp'),{recursive:true});
    provider=await openProvider({directory,port:0,ledger});
    assert.equal(JSON.parse(await readFile(join(directory,'ledger.json'),'utf8')).providerId,provider.providerId);
  });

